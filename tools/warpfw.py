def records(data):
    off, pipes = 0, []
    while off + 6 <= len(data):
        n = (data[off + 4] << 8) | data[off + 5]
        if n == 0:
            return pipes, off + 6
        if n % 8:
            sys.exit("warpfw: pipe %d is %d bytes, not whole 64-bit words" % (len(pipes), n))
        pipes.append(n)
        off = (off + 6 + n + 3) & ~3
    sys.exit("warpfw: no end record")


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    fw, name, out = sys.argv[1:]
    data = open(fw, "rb").read()
    pipes, end = records(data)
    if any(n > 2048 for n in pipes):
        sys.exit("warpfw: a pipe is larger than the 2 KB instruction memory")
    sha = hashlib.sha256(data).hexdigest()
    lines = ["/* warp_%s.h - the Matrox %s's WARP microcode: linux-firmware's" % (name, name.upper()),
             " * matrox/%s_warp.fw (sha256 %s)," % (name, sha),
             " * Linux's binary ihex (records of a big-endian address and length, then",
             " * the data, padded to 4 bytes; one record per pipe). %d pipes, of" % len(pipes),
             " * %s bytes." % ", ".join(str(n) for n in pipes),
             " * Generated by tools/warpfw.py: do not edit.",
             " *",
             LICENCE,
             "static const unsigned char warp_%s_fw[%d] = {" % (name, len(data))]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    lines.append("};")
    open(out, "w").write("\n".join(lines) + "\n")
    print("warpfw: %s: %d pipes, %d bytes (records end at %d), sha256 %s" % (out, len(pipes), len(data), end, sha))


if __name__ == "__main__":
    main()
